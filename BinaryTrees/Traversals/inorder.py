class TreeNode:
    def __init__(self, val=0, left=None, right=None):
        self.val = val
        self.left = left
        self.right = right
class Solution:
    def inorderTraversal(self, root: Optional[TreeNode]) -> List[int]:
        
        def inorder(root, out):
            if not root:
                return out
            
            inorder(root.left, out)
            out.append(root.val)
            inorder(root.right, out)
            return out
        
        return inorder(root, [])
    
